import { Router } from "express";
import { pool } from "../db";
import { requireAuth } from "../auth";
import { isAutoGeneratedUsername, isValidUsername } from "../validation";

export const meRouter = Router();

meRouter.get("/api/me", requireAuth, async (req, res) => {
  try {
    const result = await pool.query(
      `SELECT id, username, display_name, email, avatar_s3_key, created_at
       FROM users
       WHERE cognito_sub = $1`,
      [req.cognitoSub],
    );

    const user = result.rows[0];
    if (!user) {
      res.status(404).json({ error: "No profile found for this account yet" });
      return;
    }

    res.status(200).json({ ...user, needs_username: isAutoGeneratedUsername(user.username) });
  } catch (err) {
    console.error("GET /api/me failed:", err instanceof Error ? err.message : err);
    res.status(500).json({ error: "Failed to load profile" });
  }
});

meRouter.put("/api/me/username", requireAuth, async (req, res) => {
  try {
    const currentResult = await pool.query(`SELECT id, username FROM users WHERE cognito_sub = $1`, [
      req.cognitoSub,
    ]);
    const current = currentResult.rows[0];
    if (!current) {
      res.status(404).json({ error: "No profile found for this account yet" });
      return;
    }

    // Username is immutable after it's genuinely been chosen (PRD F1) — this
    // endpoint only exists to let a real one replace the auto-generated
    // fallback once, since Cognito's Hosted UI never gives real signups a
    // chance to set one at signup time.
    if (!isAutoGeneratedUsername(current.username)) {
      res.status(403).json({ error: "Username has already been set and cannot be changed" });
      return;
    }

    const username = req.body?.username;
    if (!isValidUsername(username)) {
      res
        .status(400)
        .json({ error: "Username must be 3-20 characters, lowercase letters/numbers/underscore only" });
      return;
    }

    const result = await pool.query(
      `UPDATE users SET username = $1 WHERE id = $2
       RETURNING id, username, display_name, email, avatar_s3_key, created_at`,
      [username, current.id],
    );

    res.status(200).json({ ...result.rows[0], needs_username: false });
  } catch (err) {
    if (typeof err === "object" && err !== null && (err as { code?: string }).code === "23505") {
      res.status(409).json({ error: "That username is already taken" });
      return;
    }
    console.error("PUT /api/me/username failed:", err instanceof Error ? err.message : err);
    res.status(500).json({ error: "Failed to update username" });
  }
});
